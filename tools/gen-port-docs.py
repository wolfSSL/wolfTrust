"""docs/Ports.md from the port registry.

Every port is described once, in port/<soc>/port.json; this renders the
page that lists them (board, guide, CI label and image, engines and build
variants, the emulator smoke tier, the hardware qualification extras and the
capabilities the port declares absent). `--check` fails when the committed
page is stale, so a port PR regenerates it instead of editing it by hand.

    tools/gen-port-docs.py            write docs/Ports.md
    tools/gen-port-docs.py --check    exit 1 when docs/Ports.md differs
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "tests", "target", "lib"))
import scenario_matrix  # noqa: E402
import scenarios  # noqa: E402

OUT = os.path.join(REPO, "docs", "Ports.md")


def render():
    lines = ["# Ports", "",
             "Generated by `tools/gen-port-docs.py` from `port/<soc>/port.json`;",
             "`make test` fails when this page is stale. Register a port there and",
             "regenerate this page instead of editing it.", "",
             "| Port | Board | Guide | CI label | Engines | Variants | Image |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for name in sorted(scenario_matrix.PORTS):
        d = scenario_matrix.PORTS[name]["def"]
        guide = os.path.basename(d["guide"])
        lines.append("| `%s` | %s | [%s](%s) | `%s`%s | %s | %s | `%s` |" % (
            name, d["board"], d["display"], guide, d["ci"]["label"],
            " (label only)" if d["ci"].get("label_only") else "",
            ", ".join(d["build"]["engines"]), ", ".join(d["build"].get("variants", [])) or "none",
            d["ci"]["image"]))
    lines += ["", "## Emulator scenarios", "",
              "Every port's full tier is in `port.json` (`m33mu.groups`). The smoke tier",
              "runs on every pull request for a port whose CI label is optional; a port",
              "marked label only above runs only under its label. Capabilities a port",
              "declares absent exempt the scenarios that need them and mark their",
              "assertion blocks N/A.", "",
              "| Port | Smoke tier | Absent capabilities |",
              "| --- | --- | --- |"]
    for name in sorted(scenario_matrix.PORTS):
        m = scenario_matrix.PORTS[name]["def"]["m33mu"]
        absent = ", ".join("`%s`" % c for c in sorted(m.get("caps_absent", {}))) or "none"
        lines.append("| `%s` | %s | %s |" % (name, " ".join("`%s`" % s for s in m["smoke"]), absent))
    lines += ["", "## Hardware", "",
              "Every board runs the eight-scenario minimum (%s)." %
              ", ".join("`%s`" % s for s in scenarios.HARDWARE_MINIMUM),
              "`make test-hardware TARGET=<soc> WT_HW_TIER=qualification` adds the extras below.", "",
              "| Port | Qualification extras | Opt-in | Fixture |",
              "| --- | --- | --- | --- |"]
    for name in sorted(scenario_matrix.PORTS):
        hw = scenario_matrix.PORTS[name]["def"].get("hardware", {})
        lines.append("| `%s` | %s | %s | %s |" % (
            name, " ".join("`%s`" % s for s in hw.get("qualification", [])) or "none",
            " ".join("`%s`" % s for s in hw.get("optin", [])) or "none",
            hw.get("fixture", "")))
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = open(OUT).read() if os.path.isfile(OUT) else ""
        if current != text:
            print("docs/Ports.md is stale; run tools/gen-port-docs.py", file=sys.stderr)
            return 1
        print("docs/Ports.md is current")
        return 0
    with open(OUT, "w") as handle:
        handle.write(text)
    print("wrote docs/Ports.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
